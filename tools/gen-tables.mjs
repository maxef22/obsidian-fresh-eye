/**
 * Generates src/core/tables.ts from the reference Go implementation
 * (https://gitlab.com/opennota/fresheye, AGPL-3.0).
 *
 * The two tables are hand-tuned data, so they are extracted mechanically
 * instead of being retyped: a typo in a single cell would silently change
 * detection quality.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const SRC = 'obs-plugin/vendor-src/context.go';
const OUT = 'obs-plugin/src/core/tables.ts';

const go = await readFile(SRC, 'utf8');

function block(varName) {
  const startToken = `var ${varName} = []int{`;
  const start = go.indexOf(startToken);
  if (start < 0) throw new Error(`block ${varName} not found`);
  const end = go.indexOf('\n}', start);
  if (end < 0) throw new Error(`end of ${varName} not found`);
  return go.slice(start + startToken.length, end);
}

function numbers(raw) {
  const noBlockComments = raw.replace(/\/\*[\s\S]*?\*\//g, ' ');
  const noLineComments = noBlockComments.replace(/\/\/[^\n]*/g, ' ');
  return (noLineComments.match(/-?\d+/g) ?? []).map(Number);
}

const simCh = numbers(block('simCh'));
const infLetters = numbers(block('infLetters'));

// Legitimate Russian pairs that look similar but must not be reported.
const excStart = go.indexOf('var exceptions = map[string]bool{');
if (excStart < 0) throw new Error('exceptions block not found');
const excEnd = go.indexOf('\n}', excStart);
const exceptions = [...go.slice(excStart, excEnd).matchAll(/"([^"]+)"/g)].map((m) => m[1]);

const STRIDE = 64;
const ALPHABET = 34;

if (simCh.length !== STRIDE * ALPHABET) {
  throw new Error(`simCh: expected ${STRIDE * ALPHABET} values, got ${simCh.length}`);
}
if (infLetters.length !== ALPHABET * 2) {
  throw new Error(`infLetters: expected ${ALPHABET * 2} values, got ${infLetters.length}`);
}

// Structural checks: every row is 34 data cells padded to the stride with zeros,
// the diagonal is the self-similarity value, and the matrix is symmetric.
for (let r = 0; r < ALPHABET; r++) {
  const row = simCh.slice(r * STRIDE, r * STRIDE + STRIDE);
  if (row.slice(ALPHABET).some((v) => v !== 0)) {
    throw new Error(`simCh row ${r}: padding is not zero`);
  }
  // Index 32 is a placeholder for anything that is not a Russian letter and is all zeros.
  if (r !== 32 && row[r] !== 9) {
    throw new Error(`simCh row ${r}: diagonal is ${row[r]}, expected 9`);
  }
  for (let c = 0; c < ALPHABET; c++) {
    if (row[c] !== simCh[c * STRIDE + r]) {
      throw new Error(`simCh is not symmetric at (${r},${c})`);
    }
  }
}

function format(array, perLine) {
  const lines = [];
  for (let i = 0; i < array.length; i += perLine) {
    lines.push('  ' + array.slice(i, i + perLine).join(', ') + ',');
  }
  return lines.join('\n');
}

const header = `/**
 * Similarity tables for Russian letters.
 *
 * Auto-generated by tools/gen-tables.mjs from the reference implementation
 * https://gitlab.com/opennota/fresheye (AGPL-3.0), itself a port of
 * "Свежий взгляд" by Maxim Kirsanov. Do not edit by hand.
 *
 * Letter indices follow the Russian alphabet order used by the original:
 * а б в г д е ж з и й к л м н о п р с т у ф х ц ч ш щ ъ ы ь э ю я . ё
 */

/** Width of a row in {@link SIM_CH}; rows are padded with zeros. */
export const SIM_CH_STRIDE = ${STRIDE};

/** Number of letter slots, including the placeholder at index 32. */
export const ALPHABET_SIZE = ${ALPHABET};

/**
 * Weighted similarity of two letters: 9 means the same letter, 0 means
 * unrelated. Empty cells are the zero padding of the stride.
 */
export const SIM_CH = Int16Array.from([
${format(simCh, 18)}
]);

/**
 * How much each letter contributes to the "informativeness" of a word.
 * Two weights per letter: for the first position and for the rest.
 */
export const INF_LETTERS = Int32Array.from([
${format(infLetters, 10)}
]);

/** Pairs of similar-looking words that are legitimate Russian and must not be reported. */
export const EXCEPTIONS: ReadonlySet<string> = new Set([
${exceptions.map((e) => `  ${JSON.stringify(e)},`).join('\n')}
]);

/** Second words of {@link EXCEPTIONS}: a fast pre-check before the full lookup. */
export const EXCEPTION_SECONDS: ReadonlySet<string> = new Set([
${[...new Set(exceptions.map((e) => e.split(' ')[1]))].map((e) => `  ${JSON.stringify(e)},`).join('\n')}
]);
`;

await mkdir('obs-plugin/src/core', { recursive: true });
await writeFile(OUT, header);
console.log(`wrote ${OUT}: simCh=${simCh.length}, infLetters=${infLetters.length}`);
